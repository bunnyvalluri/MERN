/**
 * Returns dynamic internships with live rolling timestamps relative to now.
 * Ensures the platform always feels active 24/7 with fresh "Just now", "2 hours ago",
 * "Today", and "Yesterday" relative timestamps.
 */
export function getDynamicRealInternships() {
  const now = Date.now();

  return RAW_INTERNSHIPS_DATA.map((item, index) => {
    const comp = companyMap.get(item.companySlug) || {
      _id: `comp_${item.companySlug}`,
      name: item.companySlug,
      slug: item.companySlug,
      logo: 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?w=200&auto=format&fit=crop&q=80',
      industry: 'Technology',
      verified: true
    };

    // Calculate rolling dynamic timestamps based on offsetHours
    // item.offsetHours (0 to 420 hours)
    const hoursAgo = item.offsetHours !== undefined ? item.offsetHours : (index * 6 + 1);
    const createdTimestamp = new Date(now - hoursAgo * 3600 * 1000).toISOString();
    
    const deadlineDaysAhead = item.deadlineDays || (45 + (index % 60));
    const deadlineTimestamp = new Date(now + deadlineDaysAhead * 24 * 3600 * 1000).toISOString();

    const _id = `int_${item.slug}`;

    return {
      _id,
      id: _id,
      companyId: comp,
      company: comp.name,
      companySlug: comp.slug,
      companyLogo: comp.logo,
      title: item.title,
      slug: item.slug,
      description: item.description,
      responsibilities: item.responsibilities || [],
      requirements: item.requirements || [],
      skills: item.skills || [],
      location: item.location || { city: 'San Francisco', state: 'CA', country: 'United States' },
      remote: item.remote || 'REMOTE',
      type: item.type || 'FULL_TIME',
      duration: item.duration || '3 Months (Summer 2026)',
      stipend: item.stipend || { amount: 8500, currency: 'USD', period: 'MONTH', isUnpaid: false },
      openings: item.openings || 5,
      applicationDeadline: deadlineTimestamp,
      status: 'PUBLISHED',
      category: item.category || 'Software Engineering',
      featured: Boolean(item.featured),
      viewsCount: item.viewsCount || 1000,
      applicationsCount: item.applicationsCount || 40,
      createdAt: createdTimestamp,
      updatedAt: createdTimestamp,
    };
  });
}

export const REAL_INTERNSHIPS = getDynamicRealInternships();

/**
 * Filter, search, sort, and paginate through real internships dataset in-memory.
 */
export function queryRealInternships(params = {}, savedIds = new Set()) {
  // Generate freshly computed dynamic timestamps
  let list = getDynamicRealInternships();

  // 1. Keyword search (title, company name, skills, description)
  if (params.search && params.search.trim()) {
    const q = params.search.trim().toLowerCase();
    list = list.filter((item) => {
      const title = (item.title || '').toLowerCase();
      const compName = (item.companyId?.name || item.company || '').toLowerCase();
      const desc = (item.description || '').toLowerCase();
      const cat = (item.category || '').toLowerCase();
      const skillsMatch = (item.skills || []).some((s) => s.toLowerCase().includes(q));
      return (
        title.includes(q) ||
        compName.includes(q) ||
        desc.includes(q) ||
        cat.includes(q) ||
        skillsMatch
      );
    });
  }

  // 2. Location filter
  if (params.location && params.location.trim()) {
    const loc = params.location.trim().toLowerCase();
    list = list.filter((item) => {
      const city = (item.location?.city || '').toLowerCase();
      const state = (item.location?.state || '').toLowerCase();
      const country = (item.location?.country || '').toLowerCase();
      return city.includes(loc) || state.includes(loc) || country.includes(loc);
    });
  }

  // 3. Remote filter
  if (params.remote && params.remote !== 'ALL' && params.remote !== 'all') {
    list = list.filter((item) => item.remote === params.remote);
  }

  // 4. Type filter (FULL_TIME / PART_TIME)
  if (params.type && params.type !== 'ALL' && params.type !== 'all') {
    list = list.filter((item) => item.type === params.type);
  }

  // 5. Category filter
  if (params.category && params.category !== 'ALL' && params.category !== 'all') {
    list = list.filter((item) => item.category === params.category);
  }

  // 6. Min/Max Stipend
  if (params.minStipend) {
    const min = Number(params.minStipend);
    if (!isNaN(min)) {
      list = list.filter((item) => (item.stipend?.amount || 0) >= min);
    }
  }
  if (params.maxStipend) {
    const max = Number(params.maxStipend);
    if (!isNaN(max)) {
      list = list.filter((item) => (item.stipend?.amount || 0) <= max);
    }
  }

  // 7. Skills filter
  if (params.skills && params.skills.trim()) {
    const requiredSkills = params.skills
      .split(',')
      .map((s) => s.trim().toLowerCase())
      .filter(Boolean);
    if (requiredSkills.length > 0) {
      list = list.filter((item) =>
        requiredSkills.some((req) =>
          item.skills.some((s) => s.toLowerCase() === req)
        )
      );
    }
  }

  // 8. Date Posted filter
  if (params.datePosted && params.datePosted !== 'all') {
    const now = Date.now();
    const mapDays = { '24h': 1, '7d': 7, '14d': 14, '30d': 30 };
    const maxDays = mapDays[params.datePosted];
    if (maxDays) {
      const cutoff = now - maxDays * 24 * 3600 * 1000;
      list = list.filter((item) => new Date(item.createdAt).getTime() >= cutoff);
    }
  }

  // 9. Sort By
  const sortBy = params.sortBy || 'latest';
  if (sortBy === 'deadline') {
    list.sort((a, b) => new Date(a.applicationDeadline) - new Date(b.applicationDeadline));
  } else if (sortBy === 'stipend_high') {
    list.sort((a, b) => (b.stipend?.amount || 0) - (a.stipend?.amount || 0));
  } else if (sortBy === 'stipend_low') {
    list.sort((a, b) => (a.stipend?.amount || 0) - (b.stipend?.amount || 0));
  } else if (sortBy === 'popularity') {
    list.sort((a, b) => (b.viewsCount || 0) - (a.viewsCount || 0));
  } else {
    // latest
    list.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
  }

  const total = list.length;
  const page = Math.max(1, parseInt(params.page, 10) || 1);
  const limit = Math.max(1, parseInt(params.limit, 10) || 12);
  const skip = (page - 1) * limit;

  const paginated = list.slice(skip, skip + limit).map((item) => ({
    ...item,
    isSaved: savedIds.has(item._id || item.id),
  }));

  return {
    data: paginated,
    page,
    limit,
    total,
    totalPages: Math.ceil(total / limit) || 1,
  };
}

export function getRealInternshipById(idOrSlug, savedIds = new Set()) {
  const dynamicList = getDynamicRealInternships();
  const found = dynamicList.find(
    (item) =>
      item._id === idOrSlug ||
      item.id === idOrSlug ||
      item.slug === idOrSlug.toLowerCase()
  );
  if (!found) return null;
  return {
    internship: {
      ...found,
      isSaved: savedIds.has(found._id || found.id),
    },
    isSaved: savedIds.has(found._id || found.id),
    hasApplied: false,
  };
}
